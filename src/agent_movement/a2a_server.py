JSONRPC_PATH = "/a2a/jsonrpc"
REST_PREFIX = "/a2a/rest"
# A2A v1.0 sec. 8.6.1: the Agent Card endpoint SHOULD send Cache-Control with max-age (the SDK
# always sends a content-hash ETag). The card is fixed for the life of the process; the short
# max-age covers a restart on the same port with different --advertise or contextId options.
AGENT_CARD_CACHE_CONTROL = "public, max-age=60"


def build_agent_card(base_url: str, receiver_id: str, kinds: list[str],
                     client_context_id: str = CLIENT_CONTEXT_REJECTED) -> AgentCard:
    """Agent Card for the destination worker; advertises only the enabled kinds.

    ``client_context_id`` is the policy for a client-supplied ``contextId`` under
    the current profile URI; it is published in the extension ``params`` so a
    client knows how the server handles one before sending it (A2A v1.0 sec. 3.4.1).
    """
    if client_context_id not in CLIENT_CONTEXT_POLICIES:
        raise ValueError("client_context_id must be one of " + ", ".join(CLIENT_CONTEXT_POLICIES))
    skills = [AgentSkill(
        id=skill_id(kind), name=f"Delegated {kind}",
        description=(f"Pure, allowlisted '{kind}' over synthetic/public text, executed only with a "
                     "receiver-side approval. No tools, no side effects."),
        tags=["agent-movement", "delegation", "experimental"],
        input_modes=[TASK_MEDIA_TYPE], output_modes=[RECEIPT_MEDIA_TYPE]) for kind in kinds]
    profile = AgentExtension(
        uri=EXTENSION_URI, required=True,
        description=("Experimental agent-movement handoff profile: envelope fields in "
                     "Message.metadata, one structured task part, receipt artifact. "
                     "Specification at the extension URI."),
        params={"profile_version": PROFILE_VERSION, "schema_version": SCHEMA_VERSION,
                "operations": ["delegate"], "destination_agent_id": receiver_id,
                "context_id": "server-generated", "client_context_id": client_context_id,
                "deprecated_aliases": [LEGACY_EXTENSION_URI],
                "proves": "delegation-not-migration", "authentication": "none-experimental"})
    # Listed so profile 0.1 clients, which look for the URN on the card, keep working for one
    # profile version. Not required: activating either URI satisfies the required profile.
    legacy = AgentExtension(
        uri=LEGACY_EXTENSION_URI, required=False,
        description=(f"DEPRECATED alias of {EXTENSION_URI}, accepted in profile 0.2.x and removed "
                     "in 0.3.0. Keeps the profile 0.1 rule: a client contextId must equal the "
                     "logical task ID."),
        params={"deprecated": True, "replaced_by": EXTENSION_URI, "client_context_id": CLIENT_CONTEXT_BOUND})
    return AgentCard(
        name=f"agent-movement receiver ({receiver_id})",
        description=("Experimental local A2A destination worker. Delegation of allowlisted pure tasks "
                     "only; not migration; unauthenticated; loopback only."),
        version="0.1.0",
        supported_interfaces=[
            AgentInterface(url=base_url + JSONRPC_PATH, protocol_binding=TransportProtocol.JSONRPC,
                           protocol_version=PROTOCOL_VERSION_CURRENT),
            AgentInterface(url=base_url + REST_PREFIX, protocol_binding=TransportProtocol.HTTP_JSON,
                           protocol_version=PROTOCOL_VERSION_CURRENT),
        ],
        capabilities=AgentCapabilities(streaming=True, push_notifications=False,
                                       extended_agent_card=False, extensions=[profile, legacy]),
        default_input_modes=[TASK_MEDIA_TYPE],
        default_output_modes=[RECEIPT_MEDIA_TYPE],
        skills=skills,
    )


def decode_message(message: Message, request_metadata: Any = None, bound_task_id: str = "",
                   client_context_id: str | None = None) -> dict[str, Any]:
    """Map an inbound A2A message to a validated envelope or raise ``ContractError``.

    Same checks as :func:`decode_handoff`, which also returns the profile URI used.
    """
    return decode_handoff(message, request_metadata, bound_task_id, client_context_id)[1]


def decode_handoff(message: Message, request_metadata: Any = None, bound_task_id: str = "",
                   client_context_id: str | None = None) -> tuple[str, dict[str, Any]]:
    """Map an inbound A2A message to ``(profile URI, validated envelope)`` or raise ``ContractError``.

    ``bound_task_id`` is the server-assigned A2A task ID that the SDK writes
    into the message after admission; a client-chosen task ID is refused.
    ``client_context_id`` is the server's policy for a client-supplied
    ``contextId``; pass it only while the message still holds the contextId
    as the client sent it (the SDK later overwrites it with the generated one).
    """
    if request_metadata:
        raise ContractError("request-level metadata is not accepted")
    if message.role != Role.ROLE_USER:
        raise ContractError("handoff must be a user-role message")
    if message.task_id != bound_task_id or message.reference_task_ids:
        raise ContractError("task continuation and references are not supported")
    if len(message.extensions) != 1 or message.extensions[0] not in EXTENSION_URIS:
        raise ContractError("message must declare exactly one handoff profile extension URI")
    uri = message.extensions[0]
    if len(message.parts) != 1:
        raise ContractError("handoff message must contain exactly one part")
    part = message.parts[0]
    if (part.WhichOneof("content") != "data" or part.media_type != TASK_MEDIA_TYPE
            or part.filename or len(part.metadata)):
        raise ContractError("handoff part must be one structured task data part")
    metadata = MessageToDict(message.metadata)
    if set(metadata) != {uri}:
        raise ContractError("message metadata must contain only the declared handoff profile")
    envelope = a2a_to_envelope(metadata[uri], MessageToDict(part.data))
    if client_context_id is not None:
        check_context_id(message.context_id, envelope, context_policy(uri, client_context_id))
    return uri, envelope


class HandoffRequestHandler(DefaultRequestHandlerV2):
    """SDK request handler with profile admission before any task is created."""

    def __init__(self, *, executor: HandoffExecutor, agent_card: AgentCard,
                 kinds: list[str], log: A2ACorrelationLog,
                 client_context_id: str = CLIENT_CONTEXT_REJECTED):
        super().__init__(agent_executor=executor, task_store=InMemoryTaskStore(),
                         agent_card=agent_card, validate_input_modes=True)
        self.card = agent_card
        self.kinds = frozenset(kinds)
        self.log = log
        self.client_context_id = client_context_id

    async def _admit(self, params: SendMessageRequest, context: Any) -> None:
        # Runs before the SDK builds the RequestContext, so params.message.context_id is
        # still exactly what the client sent (empty means "server, generate one").
        message_id = params.message.message_id or "missing"
        try:
            # Core-spec checks first, with the errors A2A v1.0 assigns to them; they hold with or
            # without the profile and would otherwise be masked by the profile's InvalidParams.
            # sec. 3.1.1: a stated part media type the card does not declare ->
            # ContentTypeNotSupportedError (the same SDK check DefaultRequestHandlerV2 runs).
            validate_input_modes(params.message, self.card)
            if params.message.task_id:
                # sec. 3.4.2: an unknown taskId MUST give TaskNotFoundError. A known one names a
                # task this worker already finished (handoffs run to a terminal state), and
                # sec. 3.1.1 answers messages to terminal tasks with UnsupportedOperationError.
                if await self.task_store.get(params.message.task_id, context) is None:
                    raise TaskNotFoundError(message="task not found")
                raise UnsupportedOperationError(
                    message="task continuation is not supported by the handoff profile")
            activated = context.requested_extensions & set(EXTENSION_URIS)
            if not activated:
                raise ExtensionSupportRequiredError(
                    message=f"client must activate required extension {EXTENSION_URI}")
            try:
                uri, envelope = decode_handoff(params.message, MessageToDict(params.metadata),
                                               client_context_id=self.client_context_id)
                if uri not in activated:
                    raise ContractError("the message's profile URI was not activated in A2A-Extensions")
            except ContractError as exc:
                raise InvalidParamsError(message=f"handoff profile rejected: {exc}") from None
            if envelope["task"]["kind"] not in self.kinds:
                raise UnsupportedOperationError(
                    message="capability not advertised by this agent: " + skill_id(envelope["task"]["kind"]))
        except (ContentTypeNotSupportedError, ExtensionSupportRequiredError, InvalidParamsError,
                TaskNotFoundError, UnsupportedOperationError) as exc:
            await asyncio.to_thread(self.log.record, message_id=message_id,
                                    outcome="rejected." + type(exc).__name__)
            raise

    async def on_message_send(self, params: SendMessageRequest, context: Any) -> Message | Task:
        await self._admit(params, context)
        result: Message | Task = await super().on_message_send(params, context)
        return result

    async def on_message_send_stream(self, params: SendMessageRequest,
                                     context: Any) -> AsyncGenerator[Event, None]:
        await self._admit(params, context)
        async for event in super().on_message_send_stream(params, context):
            yield event


class HandoffExecutor(AgentExecutor):
    """Runs the unchanged core receiver; emits SUBMITTED, WORKING, artifact, terminal state."""

    def __init__(self, receiver: HandoffReceiver, log: A2ACorrelationLog):
        self.receiver = receiver
        self.log = log

    async def execute(self, context: RequestContext, event_queue: EventQueue) -> None:
        task_id, context_id = context.task_id or "", context.context_id or ""
        message = context.message
        assert message is not None  # the SDK attaches the request message to every send
        # No history is stored on the task: the A2A task store keeps IDs and results only.
        await event_queue.enqueue_event(new_task(task_id, context_id, TaskState.TASK_STATE_SUBMITTED))
        updater = TaskUpdater(event_queue, task_id, context_id)
        await updater.start_work()
        envelope, uri = None, EXTENSION_URI
        try:
            # Defense in depth. The contextId rule was applied at admission; by now the SDK has
            # replaced an absent contextId with the generated one, so it is not re-checked here.
            uri, envelope = decode_handoff(message, bound_task_id=task_id)
            if message.context_id != context_id:
                raise ContractError("message contextId differs from the task's contextId")
            receipt = await asyncio.to_thread(self.receiver.receive, envelope)
        except (ContractError, PolicyDenied, Conflict) as exc:
            reason = {PolicyDenied: "approval_denied", Conflict: "idempotency_conflict"}.get(
                type(exc), "invalid_contract")
            await asyncio.to_thread(self.log.record, message_id=message.message_id, outcome=reason,
                                    task_id=task_id, context_id=context_id, envelope=envelope)
            await updater.reject(updater.new_agent_message(
                [new_data_part({"error": reason}, media_type="application/json")]))
            return
        artifact = receipt_to_artifact(receipt)
        await updater.add_artifact(
            [new_data_part(artifact["data"], media_type=RECEIPT_MEDIA_TYPE)],
            artifact_id=artifact["artifact_id"], name=artifact["name"],
            # Keyed by the URI the client used, so profile 0.1 clients find their metadata.
            metadata={uri: artifact["metadata"]}, extensions=[uri],
            last_chunk=True)
        await asyncio.to_thread(
            self.log.record, message_id=message.message_id,
            outcome="replayed" if receipt["replayed"] else "completed", task_id=task_id,
            context_id=context_id, envelope=envelope, artifact_digest=receipt["artifact_digest"])
        await updater.complete()

    async def cancel(self, context: RequestContext, event_queue: EventQueue) -> None:
        raise UnsupportedOperationError(message="synthetic handoffs complete synchronously")


def build_app(*, db: Path, base_url: str, receiver_id: str, approvals: list[Approval],
              kinds: list[str], client_context_id: str = CLIENT_CONTEXT_REJECTED) -> Starlette:
    """Build the ASGI app. ``client_context_id`` defaults to server-generated contexts only."""
    unknown = set(kinds) - set(KINDS)
    if not kinds or unknown:
        raise ValueError("kinds must be a non-empty subset of " + ", ".join(KINDS))
    store = SQLiteStore(db)
    log = A2ACorrelationLog(db, store)
    card = build_agent_card(base_url, receiver_id, kinds, client_context_id)
    handler = HandoffRequestHandler(executor=HandoffExecutor(HandoffReceiver(receiver_id, store, approvals), log),
                                    agent_card=card, kinds=kinds, log=log,
                                    client_context_id=client_context_id)

    @contextlib.asynccontextmanager
    async def lifespan(_app: Starlette) -> AsyncIterator[None]:
        yield
        await handler.aclose()

    # The HTTP+JSON routes are mounted *under* REST_PREFIX instead of passing path_prefix: with
    # path_prefix, a2a-sdk 1.2.2 also adds a root-level Mount('/{tenant}') that captures every
    # two-segment path. That put the optional tenant segment before the interface URL (the A2A
    # v1.0 binding puts it after: <interface url>/{tenant}/message:send, a2a.proto) and swallowed
    # POST /a2a/jsonrpc/, so Starlette never sent its trailing-slash 307 to /a2a/jsonrpc and
    # the A2A TCK's JSON-RPC client (which posts to "<url>/") got a 404 (docs/a2a-adapter.md).
    routes = [*create_agent_card_routes(card, cache_control=AGENT_CARD_CACHE_CONTROL),
              *create_jsonrpc_routes(handler, JSONRPC_PATH),
              Mount(REST_PREFIX, routes=create_rest_routes(handler))]
    return Starlette(routes=routes, lifespan=lifespan)


def main() -> None:
    import uvicorn

    parser = argparse.ArgumentParser(description="Experimental A2A v1 destination worker (loopback only)")
    parser.add_argument("--db", required=True, type=Path)
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--receiver-id", default="agent-b")
    parser.add_argument("--origin-id", default="agent-a")
    parser.add_argument("--task-id", default="demo-task")
    parser.add_argument("--approval", default="demo-approval")
    parser.add_argument("--kind", choices=KINDS, default="word_count", help="approved task kind")
    parser.add_argument("--advertise", choices=KINDS, action="append",
                        help="kinds advertised as skills (default: only --kind)")
    parser.add_argument("--accept-client-context-id", action="store_true",
                        help="opt in: accept a client-supplied contextId if it equals the logical task ID "
                             "(default: contextId is server-generated and a client one is rejected)")
    options = parser.parse_args()
    approval = Approval(options.approval, options.task_id, options.origin_id, options.receiver_id,
                        options.kind, expires_at=datetime.now(UTC) + timedelta(minutes=10))
    # Intentionally impossible to bind a public interface through this CLI.
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", options.port))
    sock.listen(64)  # queue early connections until uvicorn starts accepting
    port = sock.getsockname()[1]
    base_url = f"http://127.0.0.1:{port}"
    app = build_app(db=options.db, base_url=base_url, receiver_id=options.receiver_id,
                    approvals=[approval], kinds=options.advertise or [options.kind],
                    client_context_id=(CLIENT_CONTEXT_BOUND if options.accept_client_context_id
                                       else CLIENT_CONTEXT_REJECTED))
    print(json.dumps({"port": port, "agent": options.receiver_id, "url": base_url}), flush=True)
    server = uvicorn.Server(uvicorn.Config(app, log_level="warning", access_log=False))
    with contextlib.suppress(KeyboardInterrupt):
        server.run(sockets=[sock])


if __name__ == "__main__":
    main()
