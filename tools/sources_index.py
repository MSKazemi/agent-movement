#!/usr/bin/env python3
"""Index every external URL cited in README.md and docs/ in docs/sources.md (stdlib only).

Usage:
  python3 tools/sources_index.py [--root DIR] check
  python3 tools/sources_index.py [--root DIR] generate [--refresh-dates]

`check` extracts every external URL from README.md and docs/**/*.md (minus the
excluded and generated files below) and compares it with the generated section
of docs/sources.md, between SECTION_START and SECTION_END. It exits 1 and lists
each URL that is cited but not indexed (UNINDEXED), each index row that no
document cites any more (STALE), each row without a valid access date
(NO-DATE), and any other drift such as a changed "Cited in" list. Otherwise it
exits 0. `generate` rewrites only that section and leaves the hand-written text
above and below it untouched. It appends the section at the end of the file if
the markers are missing.

The index is grouped by document. There is one row per (document, URL)
citation: the URL, every document key that cites the URL, the access date and
the basis of that date. Document keys are paths relative to docs/ without
".md" (for example `glossary` or `protocols-and-networks/README`). The root
README.md is `README`.

Access date of a new row, first match wins:
  1. citation: a date on the same line as the URL after "accessed", "retrieved",
     "visited", "checked", "fact-checked", "reviewed" or "verified". Each such
     date belongs to the closest URL on the line only. If the document cites
     the URL several times, the latest such date is used.
  2. section: the same pattern in the nearest heading above the URL, e.g.
     "## Sources (accessed 2026-10-15)".
  3. document: the date stated in the document header (the lines before the
     first "## " heading). An "accessed"/"retrieved" date wins over other
     keywords ("Last reviewed", "Reviewed on", "Research date", "Research
     snapshot", ...). Otherwise
     the first dated keyword is used.
  4. default: DEFAULT_ACCESS_DATE.
An access date already in the index is kept on every regeneration, so a date
edited by hand survives. `generate --refresh-dates` recomputes only rows whose
basis is one of the automatic bases (citation/section/document/default). Rows
with any other basis (e.g. `manual`) are always kept.

URL normalisation:
  * Markdown residue is removed: trailing . , ; : ! ? * _ ~ ' " and any
    unbalanced ) or ] (so "[x](https://a.org/b))." gives "https://a.org/b").
  * Scheme and host are lower-cased. Path, query and trailing slash are kept as
    written, because they can select different content.
  * The fragment is dropped. A fragment only scrolls within the retrieved
    resource, so "spec/#413-taskstate" and "spec/" are one source with one
    access date. Hash-routing fragments ("#/..." or "#!...") are the exception:
    they select different content, so they are kept.
Not indexed:
  * URLs inside fenced code blocks and inline code spans. These are commands,
    templates and examples (e.g. `https://pypi.org/pypi/<package>/json`), not
    citations.
  * Templates: a URL followed directly by "<", "{" or "…", or containing "…".
  * Loopback and reserved example hosts (localhost, 127.0.0.0/8, example.com,
    *.example, *.test, *.invalid, ...).
  * Links to this repository itself (SELF_REPO_RE), e.g. its issues and PRs.

Output is deterministic: groups and rows are sorted, no clock is read, and the
only dates written are the ones found in the documents or DEFAULT_ACCESS_DATE.
"""
from __future__ import annotations

import argparse
import fnmatch
import re
import sys
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parent.parent
SOURCES_REL = "docs/sources.md"

# Used only when neither the citation, its section nor the document header gives
# a date. It is the repository-wide source review date stated at the top of
# docs/sources.md ("Reviewed on 2026-10-15").
DEFAULT_ACCESS_DATE = "2026-10-15"

SECTION_START = "<!-- sources-index:start -->"
SECTION_END = "<!-- sources-index:end -->"

# Files that are scanned: README.md and every docs/**/*.md. Only Markdown is
# scanned, so data files (*.jsonl, *.csv, *.bib, *.json) are never read. These
# paths (fnmatch, "*" also matches "/") are excluded on top of that:
EXCLUDE_GLOBS = (
    # The corpora. Each record carries its own date_accessed in news.jsonl /
    # papers.jsonl and its own biblatex entry. sources.md points to the corpora
    # instead of repeating them. This tool never edits corpus files.
    "docs/news-corpus/*",
    "docs/paper-corpus/*",
    # timeline.md and coverage.md are generated by tools/corpus_analysis.py; the
    # directory's README describes them and cites no external source.
    "docs/corpus-analysis/*",
    # Generated by tools/link_health.py: per-record link checks of the corpora.
    "docs/corpus-qa/*.jsonl",
    "docs/corpus-qa/link-health-*.md",
    # Maps open questions to corpus records (AMN-/AMP- IDs). It cites no
    # external sources of its own.
    "docs/evidence-map.md",
)
# Any other Markdown file whose first lines say it is generated is skipped too.
GENERATED_RE = re.compile(r"(?i)(generated by `?tools/|do not edit by hand)")
GENERATED_SCAN_LINES = 10

SELF_REPO_RE = re.compile(r"(?i)^https?://github\.com/mskazemi/agent-movement(?:[/?#.]|$)")
PLACEHOLDER_HOST_RE = re.compile(
    r"(?i)^(localhost|127(?:\.\d+){3}|0\.0\.0\.0|\[::1\]|"
    r"(?:[\w-]+\.)*example(?:\.(?:com|org|net))?|(?:[\w-]+\.)+(?:test|invalid|localhost))$"
)

URL_RE = re.compile(r"https?://[^\s<>\"'`|{}\[\]\\^]+", re.IGNORECASE)
TRAILING = ".,;:!?*_~'\""
TEMPLATE_NEXT = "<{…"
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
INLINE_CODE_RE = re.compile(r"(`+)(.+?)\1")
HEADING_RE = re.compile(r"^ {0,3}#{1,6}\s")
ISO = r"(\d{4}-\d{2}-\d{2})"
CITE_DATE_RE = re.compile(
    r"(?i)\b(?:accessed|retrieved|visited|fact-checked|checked|reviewed|verified)"
    r"(?:\s+on)?[\s:*_()]{0,6}" + ISO
)
HEADER_DATE_RE = re.compile(
    r"(?i)\b(accessed|retrieved|visited|last reviewed|reviewed on|reviewed|research date|"
    r"research snapshot|audit date|fact-checked|checked|verified|mapped|updated|date)"
    r"(?:\s+on)?[\s:*_()]{0,6}" + ISO
)
HEADER_PRIORITY = ("accessed", "retrieved", "visited")
HEADER_MAX_LINES = 20

AUTO_BASES = ("citation", "section", "document", "default")
TABLE_HEAD = "| URL | Cited in | Accessed | Date basis |"
ROW_RE = re.compile(r"^\| <([^>]+)> \| ([^|]*) \| ([^|]*) \| ([^|]*) \|$")
GROUP_RE = re.compile(r"^### \[([^\]]+)\]\([^)]*\)$")


# -------------------------------------------------------------------- scanning

@dataclass
class Citation:
    """All occurrences of one URL in one document."""
    lines: list[int] = field(default_factory=list)
    cite_dates: list[str] = field(default_factory=list)
    section_dates: list[str] = field(default_factory=list)


@dataclass
class Doc:
    key: str
    rel: str  # path relative to the root, POSIX
    header_date: str | None
    citations: dict[str, Citation]


def doc_key(rel: str) -> str:
    if rel == "README.md":
        return "README"
    sub = rel[len("docs/"):-len(".md")]
    return "docs/README" if sub == "README" else sub


def key_order(key: str) -> tuple[int, str]:
    return (0 if key == "README" else 1, key)


def is_excluded(rel: str) -> bool:
    return any(fnmatch.fnmatchcase(rel, g) for g in EXCLUDE_GLOBS)


def doc_files(root: Path) -> list[str]:
    rels = []
    if (root / "README.md").is_file():
        rels.append("README.md")
    docs = root / "docs"
    if docs.is_dir():
        for p in docs.rglob("*.md"):
            rel = p.relative_to(root).as_posix()
            if any(part.startswith(".") for part in p.relative_to(root).parts):
                continue  # e.g. temporary docs/.verify-analysis.* directories
            if p.is_file() and not is_excluded(rel):
                rels.append(rel)
    return sorted(rels)


def strip_code(lines: list[str]) -> list[str]:
    """Blank fenced code blocks and inline code spans, keeping line and column positions."""
    out, fence = [], None
    for line in lines:
        m = FENCE_RE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                    and not line.strip().lstrip(fence[0]):
                fence = None
            out.append("")
            continue
        if m:
            fence = m.group(1)
            out.append("")
            continue
        out.append(INLINE_CODE_RE.sub(lambda c: " " * len(c.group(0)), line))
    return out


def clean_url(raw: str) -> str:
    url = raw
    while url:
        if url[-1] in TRAILING:
            url = url[:-1]
        elif url[-1] == ")" and url.count("(") < url.count(")"):
            url = url[:-1]
        elif url[-1] == "]" and url.count("[") < url.count("]"):
            url = url[:-1]
        else:
            break
    return url


def normalize(url: str) -> str | None:
    """Return the canonical form of an external URL, or None if it is not indexed."""
    if "…" in url:
        return None
    try:
        parts = urlsplit(url)
    except ValueError:
        return None
    host = (parts.hostname or "").lower()
    if not host or PLACEHOLDER_HOST_RE.match(host):
        return None
    frag = parts.fragment if parts.fragment[:1] in ("/", "!") else ""
    canon = urlunsplit((parts.scheme.lower(), parts.netloc.lower(), parts.path, parts.query, frag))
    if SELF_REPO_RE.match(canon):
        return None
    return canon


def gap(a: tuple[int, int], b: tuple[int, int]) -> int:
    """Characters between two spans on a line (0 if they touch or overlap)."""
    return max(0, b[0] - a[1], a[0] - b[1])


def assign_dates(line: str, spans: list[tuple[int, int]]) -> list[str | None]:
    """Give each dated keyword on the line to the closest URL span (ties: the earlier URL)."""
    out: list[str | None] = [None] * len(spans)
    for m in CITE_DATE_RE.finditer(line):
        best = min(range(len(spans)), key=lambda i: (gap(spans[i], m.span()), i))
        if out[best] is None or m.group(1) > out[best]:
            out[best] = m.group(1)
    return out


def header_date(lines: list[str]) -> str | None:
    head = []
    for i, line in enumerate(lines[:HEADER_MAX_LINES]):
        if i > 0 and line.startswith("## "):
            break
        head.append(line)
    found = [(m.group(1).lower(), m.group(2)) for m in HEADER_DATE_RE.finditer("\n".join(head))]
    for kw, d in found:
        if kw in HEADER_PRIORITY:
            return d
    return found[0][1] if found else None


def is_generated(lines: list[str]) -> bool:
    return any(GENERATED_RE.search(line) for line in lines[:GENERATED_SCAN_LINES])


def scan_doc(root: Path, rel: str, own_section: bool) -> Doc | None:
    lines = (root / rel).read_text(encoding="utf-8").splitlines()
    if is_generated(lines):
        return None
    if own_section:  # never count the generated index as a citation
        inside = False
        for i, line in enumerate(lines):
            if line.strip() == SECTION_START:
                inside = True
            if inside:
                lines[i] = ""
            if line.strip() == SECTION_END:
                inside = False
    code_free = strip_code(lines)
    cites: dict[str, Citation] = {}
    section_date = None
    for n, (orig, text) in enumerate(zip(lines, code_free), 1):
        if HEADING_RE.match(text):
            m = CITE_DATE_RE.search(text)
            section_date = m.group(1) if m else None
        found = []  # (url, span) of every indexed URL on this line
        for m in URL_RE.finditer(text):
            nxt = text[m.end():m.end() + 1]
            if nxt and nxt in TEMPLATE_NEXT:
                continue  # e.g. https://www.w3.org/TR/<shortname>/
            raw = clean_url(m.group(0))
            url = normalize(raw)
            if url is not None:
                found.append((url, (m.start(), m.start() + len(raw))))
        dates = assign_dates(orig, [span for _, span in found]) if found else []
        for (url, _), d in zip(found, dates):
            c = cites.setdefault(url, Citation())
            c.lines.append(n)
            if d:
                c.cite_dates.append(d)
            if section_date:
                c.section_dates.append(section_date)
    return Doc(doc_key(rel), rel, header_date(lines), cites)


def scan(root: Path) -> list[Doc]:
    docs = []
    for rel in doc_files(root):
        d = scan_doc(root, rel, own_section=(rel == SOURCES_REL))
        if d is not None and d.citations:
            docs.append(d)
    return sorted(docs, key=lambda d: key_order(d.key))


def derived_date(doc: Doc, c: Citation) -> tuple[str, str]:
    if c.cite_dates:
        return max(c.cite_dates), "citation"
    if c.section_dates:
        return max(c.section_dates), "section"
    if doc.header_date:
        return doc.header_date, "document"
    return DEFAULT_ACCESS_DATE, "default"


# --------------------------------------------------------------------- the index

@dataclass
class Row:
    url: str
    cited_in: str
    accessed: str
    basis: str
    line: int


def valid_date(s: str) -> bool:
    try:
        return bool(re.fullmatch(ISO, s)) and date.fromisoformat(s) is not None
    except ValueError:
        return False


def split_sources(text: str) -> tuple[str, str | None, str]:
    """Return (before, section-or-None, after) of sources.md."""
    lines = text.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if l.strip() == SECTION_START]
    ends = [i for i, l in enumerate(lines) if l.strip() == SECTION_END]
    if not starts or not ends or ends[0] < starts[0]:
        return text, None, ""
    s, e = starts[0], ends[0]
    return "".join(lines[:s]), "".join(lines[s:e + 1]), "".join(lines[e + 1:])


def parse_section(section: str | None) -> tuple[dict[tuple[str, str], Row], list[str]]:
    rows: dict[tuple[str, str], Row] = {}
    problems: list[str] = []
    if section is None:
        return rows, problems
    group = None
    for n, line in enumerate(section.splitlines(), 1):
        g = GROUP_RE.match(line)
        if g:
            group = g.group(1)
            continue
        if not line.startswith("| <"):
            continue
        m = ROW_RE.match(line.strip())
        if not m or group is None:
            problems.append(f"MALFORMED  sources index line {n}: {line.strip()}")
            continue
        url, cited, acc, basis = (x.strip() for x in m.groups())
        rows[(group, url)] = Row(url, cited, acc, basis, n)
    return rows, problems


def build_rows(docs: list[Doc], stored: dict[tuple[str, str], Row],
               refresh: bool) -> dict[str, list[Row]]:
    cited_by: dict[str, set[str]] = {}
    for d in docs:
        for url in d.citations:
            cited_by.setdefault(url, set()).add(d.key)
    groups: dict[str, list[Row]] = {}
    for d in docs:
        rows = []
        for url in sorted(d.citations):
            keys = ", ".join(sorted(cited_by[url], key=key_order))
            old = stored.get((d.key, url))
            keep = old is not None and valid_date(old.accessed) and old.basis \
                and not (refresh and old.basis in AUTO_BASES)
            acc, basis = (old.accessed, old.basis) if keep else derived_date(d, d.citations[url])
            rows.append(Row(url, keys, acc, basis, 0))
        groups[d.key] = rows
    return groups


def doc_link(d: Doc) -> str:
    return "../README.md" if d.rel == "README.md" else d.rel[len("docs/"):]


def render(docs: list[Doc], groups: dict[str, list[Row]]) -> str:
    n_cites = sum(len(r) for r in groups.values())
    n_urls = len({r.url for rows in groups.values() for r in rows})
    L = [
        SECTION_START,
        "<!-- Generated by tools/sources_index.py (`make sources-index`). Edit only the "
        "Accessed and Date basis cells; hand-edited dates are kept on regeneration. -->",
        "",
        "## URL index by document",
        "",
        "Every external URL cited in the README and in `docs/`, grouped by the citing document. "
        "Corpus records and generated files are excluded; see `EXCLUDE_GLOBS` in "
        "[`tools/sources_index.py`](../tools/sources_index.py). "
        "*Cited in* lists every document that cites the URL. "
        "*Accessed* is the date stated next to the citation (basis `citation`), else in its "
        "section heading (`section`), else in the document header (`document`), else the "
        f"default {DEFAULT_ACCESS_DATE} (`default`). A date stated in a document is the date "
        "the source was reviewed for that document. It is not a fresh link check. "
        "`make sources` fails when a cited URL is missing here.",
        "",
        f"**Documents:** {len(groups)} · **Citations (document, URL):** {n_cites} · "
        f"**Unique URLs:** {n_urls}",
    ]
    for d in docs:
        L += ["", f"### [{d.key}]({doc_link(d)})", "", TABLE_HEAD, "|---|---|---|---|"]
        L += [f"| <{r.url}> | {r.cited_in} | {r.accessed} | {r.basis} |" for r in groups[d.key]]
    L += ["", SECTION_END]
    return "\n".join(L) + "\n"


def compose(text: str, section: str) -> str:
    before, old, after = split_sources(text)
    if old is None:
        return text.rstrip("\n") + "\n\n" + section
    return before + section + after


# ------------------------------------------------------------------------ commands

def check(root: Path) -> int:
    path = root / SOURCES_REL
    if not path.is_file():
        print(f"check: {SOURCES_REL} not found under {root}")
        return 1
    text = path.read_text(encoding="utf-8")
    _, section, _ = split_sources(text)
    stored, problems = parse_section(section)
    docs = scan(root)
    expected = render(docs, build_rows(docs, stored, refresh=False))
    if section is None:
        problems.append(f"NO-SECTION {SOURCES_REL} has no {SECTION_START} ... {SECTION_END} section")
    cited = {(d.key, url): (d, c) for d in docs for url, c in d.citations.items()}
    unindexed = sorted(set(cited) - set(stored), key=lambda k: (key_order(k[0]), k[1]))
    stale = sorted(set(stored) - set(cited), key=lambda k: (key_order(k[0]), k[1]))
    for k in unindexed:
        d, c = cited[k]
        print(f"UNINDEXED  {d.rel}:{c.lines[0]}  {k[1]}")
    for k in stale:
        print(f"STALE      [{k[0]}] {k[1]} (sources index line {stored[k].line}): no longer cited")
    no_date = [k for k, r in sorted(stored.items(), key=lambda kv: (key_order(kv[0][0]), kv[0][1]))
               if k in cited and (not valid_date(r.accessed) or not r.basis)]
    for k in no_date:
        print(f"NO-DATE    [{k[0]}] {k[1]}: access date {stored[k].accessed!r}, "
              f"basis {stored[k].basis!r}")
    for p in problems:
        print(p)
    n_urls = len({u for _, u in cited})
    failed = bool(unindexed or stale or no_date or problems)
    if not failed and section != expected:
        print(f"DRIFT      the generated section of {SOURCES_REL} differs from a fresh render "
              "(e.g. a changed 'Cited in' list or header count)")
        failed = True
    summary = (f"{len(cited)} citations of {n_urls} unique URLs in {len(docs)} documents; "
               f"{len(unindexed)} unindexed, {len(stale)} stale")
    if failed:
        print(f"sources: FAIL ({summary}). Run 'make sources-index' and review the diff.")
        return 1
    print(f"sources: ok ({summary})")
    return 0


def generate(root: Path, refresh: bool) -> int:
    path = root / SOURCES_REL
    text = path.read_text(encoding="utf-8")
    _, section, _ = split_sources(text)
    stored, problems = parse_section(section)
    for p in problems:
        print(p)
    docs = scan(root)
    groups = build_rows(docs, stored, refresh)
    new = compose(text, render(docs, groups))
    if new != text:
        path.write_text(new, encoding="utf-8", newline="\n")
    n = sum(len(r) for r in groups.values())
    print(f"wrote {path} ({n} citations in {len(groups)} documents)")
    return 1 if problems else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="repository root holding README.md and docs/ (default: this repo)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="fail if a cited URL is not indexed or the index is stale")
    g = sub.add_parser("generate", help="rewrite the generated section of docs/sources.md")
    g.add_argument("--refresh-dates", action="store_true",
                   help="recompute dates of rows with an automatic basis; keep other rows' dates")
    a = ap.parse_args(argv)
    root = a.root.resolve()
    return check(root) if a.cmd == "check" else generate(root, a.refresh_dates)


if __name__ == "__main__":
    sys.exit(main())
